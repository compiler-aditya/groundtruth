"""GroundTruth web app: pick the demo package or upload captures, watch the agent work, browse the findings.

Each run is one streaming request (newline-delimited JSON, see gt/live.py), so it works on a serverless host
where consecutive requests may reach different instances. The static UI is in public/.

  .venv/bin/uvicorn app:app --port 8000      # then open http://localhost:8000

Guards for a public deployment, all per instance: at most GT_MAX_CONCURRENT live runs at once (default 3) and
GT_RUNS_PER_HOUR per visitor (default 8); uploads limited to GT_MAX_FILES files (default 8) of photos or PDFs;
GT_UPLOAD_CODE, if set, is required for uploads. Video uploads only work where ffmpeg is installed (not Vercel).
The floor plan studio's design assistant (/api/plan/assist) counts against the same run limits.
"""

import csv
import io
import json
import os
import queue
import re
import shutil
import tempfile
import threading
import time
import uuid
from collections import defaultdict, deque
from pathlib import Path
from typing import Callable

from fastapi import FastAPI, File, Form, HTTPException, Request, UploadFile
from fastapi.responses import FileResponse, RedirectResponse, StreamingResponse
from fastapi.staticfiles import StaticFiles

from gt.floorplan import clean
from gt.live import LiveRun
from gt.package import Package
from gt.planner import run_planner
from gt.simulate import DAYS, simulate

ROOT = Path(__file__).resolve().parent
HOSTED = bool(os.environ.get("VERCEL"))
WORK = Path(tempfile.gettempdir()) / "groundtruth" if HOSTED else ROOT / "out" / "web"
CACHE = WORK / "cache" if HOSTED else ROOT / "out" / "cache"
SEED = ROOT / "seed_cache" if (ROOT / "seed_cache").exists() else None
PACKAGES = {"demo-solar": ROOT / "projects" / "demo-solar"}
MAX_CONCURRENT = int(os.environ.get("GT_MAX_CONCURRENT", 3))
RUNS_PER_HOUR = int(os.environ.get("GT_RUNS_PER_HOUR", 8))
MAX_FILES = int(os.environ.get("GT_MAX_FILES", 8))
MAX_FILE_MB = 4.0
UPLOAD_CODE = os.environ.get("GT_UPLOAD_CODE", "")
VIDEO_OK = not HOSTED and shutil.which("ffmpeg") is not None
TYPES = {"drone_still", "nameplate_photo", "drawing_sheet", "walkthrough_video"}

app = FastAPI(title="GroundTruth")
_lock = threading.Lock()
_active = 0
_recent: dict[str, deque] = defaultdict(deque)


def _admit(request: Request) -> None:
    """Per-instance limits on live runs; raises 429 when exceeded."""
    global _active
    visitor = (request.headers.get("x-forwarded-for") or (request.client.host if request.client else "?")).split(",")[0]
    now = time.time()
    with _lock:
        recent = _recent[visitor]
        while recent and now - recent[0] > 3600:
            recent.popleft()
        if _active >= MAX_CONCURRENT:
            raise HTTPException(429, "Too many runs in progress right now. Try again in a minute, or play the recorded run.")
        if len(recent) >= RUNS_PER_HOUR:
            raise HTTPException(429, f"Limit of {RUNS_PER_HOUR} live runs per hour reached. The recorded run is always available.")
        recent.append(now)
        _active += 1


def _release(_report=None) -> None:
    global _active
    with _lock:
        _active = max(0, _active - 1)


def _credits() -> dict:
    manifest = ROOT / "samples" / "real" / "manifest.json"
    if not manifest.exists():
        return {}
    return {f["path"]: f for f in json.loads(manifest.read_text())["files"]}


@app.get("/api/health")
def health() -> dict:
    return {"ok": True, "hosted": HOSTED, "keys": {"meta": bool(os.environ.get("MODEL_API_KEY")),
                                                    "baseten": bool(os.environ.get("BASETEN_API_KEY"))},
            "upload_code_required": bool(UPLOAD_CODE), "video_uploads": VIDEO_OK, "max_files": MAX_FILES,
            "max_file_mb": MAX_FILE_MB}


def _public(package: Package, name: str | None) -> dict:
    """What the UI shows about a package: captures (with thumbnails and credits for a known one) and its design rows."""
    credits = _credits()
    captures = []
    for item in package.items.values():
        rel = str(item.path).split("samples/real/")[-1] if "samples/real/" in str(item.path) else ""
        credit = credits.get(rel, {})
        captures.append({**item.public(), "thumb": f"/thumbs/{name}/{item.id}.jpg" if name else None,
                         "credit": credit.get("credit", "synthetic test image, generated by day1/make_samples.py" if not rel else ""),
                         "license": credit.get("license", "" if rel else "own work")})
    return {"id": name, "name": package.name, "description": package.description, "captures": captures,
            "quantities": package.quantities, "schedule": package.schedule, "register": package.register,
            "site_notes": package.site_notes}


@app.get("/api/packages/{name}")
def package_info(name: str) -> dict:
    if name not in PACKAGES:
        raise HTTPException(404, "unknown package")
    package = Package.load(PACKAGES[name])
    expected = package.root / "expected_findings.json"
    return {**_public(package, name), "planted": json.loads(expected.read_text()) if expected.exists() else None,
            "walk_video": f"/media/{name}/walk.mp4"}


def _stream(run: LiveRun, intro: dict) -> StreamingResponse:
    return StreamingResponse(run.stream(intro), media_type="application/x-ndjson",
                             headers={"Cache-Control": "no-store", "X-Accel-Buffering": "no"})


@app.post("/api/run")
async def run_demo(request: Request) -> StreamingResponse:
    body = await request.json()
    name = body.get("package", "demo-solar")
    if name not in PACKAGES:
        raise HTTPException(404, "unknown package")
    package = Package.load(PACKAGES[name])
    _admit(request)
    run_dir = WORK / "runs" / f"{name}-{uuid.uuid4().hex[:8]}"
    run = LiveRun(package, run_dir, CACHE, seed_cache=SEED, mode="live", on_finish=_release)
    return _stream(run, {"package": name, "name": package.name, "captures": len(package.items),
                         "package_info": _public(package, name)})


def _csv_rows(text: str, required: set[str], label: str) -> list[dict]:
    if not text.strip():
        return []
    if len(text) > 50_000:
        raise HTTPException(400, f"{label} is too long")
    rows = list(csv.DictReader(io.StringIO(text.strip())))
    missing = required - set(rows[0].keys() if rows else [])
    if missing:
        raise HTTPException(400, f"{label} needs the column(s) {sorted(missing)}")
    return rows


@app.post("/api/run-upload")
async def run_upload(
    request: Request,
    name: str = Form("My site check"),
    meta: str = Form(...),
    schedule_csv: str = Form(""),
    quantities_csv: str = Form(""),
    register_csv: str = Form(""),
    site_notes: str = Form(""),
    code: str = Form(""),
    files: list[UploadFile] = File(...),
) -> StreamingResponse:
    if UPLOAD_CODE and code != UPLOAD_CODE:
        raise HTTPException(403, "This deployment needs an access code for uploads.")
    info = json.loads(meta)
    if not files or len(files) > MAX_FILES or len(info) != len(files):
        raise HTTPException(400, f"Send 1-{MAX_FILES} files, each with a type.")
    _csv_rows(schedule_csv, {"tag"}, "Equipment schedule")
    _csv_rows(quantities_csv, {"item_id", "area", "description", "count_what", "unit", "design_qty", "method", "tolerance_pct"}, "Quantities")
    _csv_rows(register_csv, {"sheet_number", "title", "current_revision", "drawing_id"}, "Drawing register")

    root = WORK / "uploads" / uuid.uuid4().hex[:10]
    (root / "captures").mkdir(parents=True)
    (root / "design").mkdir()
    captures, drawings = [], []
    for n, (upload, m) in enumerate(zip(files, info), start=1):
        kind = m.get("type", "")
        if kind not in TYPES or (kind == "walkthrough_video" and not VIDEO_OK):
            raise HTTPException(400, f"{upload.filename}: type {kind!r} is not available here")
        data = await upload.read()
        if len(data) > MAX_FILE_MB * 1e6 * (25 if kind == "walkthrough_video" else 1):
            raise HTTPException(400, f"{upload.filename} is too large")
        suffix = Path(upload.filename or "").suffix.lower() or ".jpg"
        if suffix not in {".jpg", ".jpeg", ".png", ".pdf", ".tif", ".tiff", ".mp4", ".mov"}:
            raise HTTPException(400, f"{upload.filename}: unsupported file type")
        prefix = {"drone_still": "DRN", "nameplate_photo": "NP", "drawing_sheet": "DWG", "walkthrough_video": "WLK"}[kind]
        cid = f"{prefix}-{n:02d}"
        (root / "captures" / f"{cid}{suffix}").write_bytes(data)
        entry = {"id": cid, "path": f"captures/{cid}{suffix}", "label": re.sub(r"[^\w .,-]", "", m.get("label", ""))[:80]}
        if kind == "drawing_sheet":
            drawings.append(entry)
        else:
            captures.append({**entry, "type": kind, "area": re.sub(r"[^\w .,-]", "", m.get("area", ""))[:60]})
    design = {}
    for key, text, filename in (("equipment_schedule", schedule_csv, "equipment_schedule.csv"),
                                ("quantities", quantities_csv, "quantities.csv"),
                                ("drawing_register", register_csv, "drawing_register.csv")):
        if text.strip():
            (root / "design" / filename).write_text(text.strip() + "\n")
            design[key] = f"design/{filename}"
    if site_notes.strip():
        (root / "design" / "site_notes.md").write_text(site_notes[:5000])
        design["site_notes"] = "design/site_notes.md"
    (root / "project.json").write_text(json.dumps({
        "name": re.sub(r"[^\w .,:()-]", "", name)[:80] or "My site check",
        "description": "Uploaded through the GroundTruth web app.", "design": design,
        "drawings": drawings, "captures": captures}, indent=1))
    try:
        package = Package.load(root)
    except (ValueError, KeyError) as error:
        raise HTTPException(400, str(error))
    _admit(request)
    run = LiveRun(package, root / "run", CACHE, seed_cache=SEED, mode="live", on_finish=_release)
    return _stream(run, {"package": "upload", "name": package.name, "captures": len(package.items),
                         "package_info": _public(package, None)})


def _job(work: Callable[[Callable[[dict], None]], dict], intro: dict) -> StreamingResponse:
    """Streams one admitted job as NDJSON: start, the events work() emits, then done (or error). Frees the run slot."""
    events: queue.Queue = queue.Queue()
    started = time.time()

    def emit(event: dict) -> None:
        events.put({"t": round(time.time() - started, 2), **event})

    def runner() -> None:
        try:
            emit({"type": "done", **work(emit)})
        except BaseException as error:  # includes SystemExit from a missing API key
            emit({"type": "error", "message": f"{type(error).__name__}: {error}"[:400]})
        finally:
            _release()
            events.put(None)

    def lines():
        emit({"type": "start", **intro})
        threading.Thread(target=runner, daemon=True).start()
        while True:
            try:
                event = events.get(timeout=10)
            except queue.Empty:
                yield json.dumps({"t": round(time.time() - started, 2), "type": "ping"}) + "\n"
                continue
            if event is None:
                return
            yield json.dumps(event, ensure_ascii=False) + "\n"

    return StreamingResponse(lines(), media_type="application/x-ndjson", headers={"Cache-Control": "no-store", "X-Accel-Buffering": "no"})


@app.post("/api/plan/assist")
async def plan_assist(request: Request) -> StreamingResponse:
    """The design assistant: Muse Wonder lays out a new plan, or changes the given one, from a description."""
    body = await request.json()
    text = re.sub(r"\s+", " ", str(body.get("request") or "")).strip()
    if not 3 <= len(text) <= 800:
        raise HTTPException(400, "Describe what you want in 3 to 800 characters.")
    mode = body.get("mode") if body.get("mode") in ("edit", "improve") else "new"
    plan = clean(body.get("plan")) if mode != "new" else None
    simulation = None
    if mode == "improve":
        if not plan["rooms"]:
            raise HTTPException(400, "There is no plan to improve.")
        settings = body.get("settings") or {}
        try:
            simulation = {"latitude": min(66.0, max(-66.0, float(settings.get("latitude", 28.6)))),
                          "day": DAYS.get(settings.get("season"), DAYS["winter"]), "north": float(settings.get("north", 0)) % 360}
        except (TypeError, ValueError):
            raise HTTPException(400, "latitude and north must be numbers")
    _admit(request)
    return _job(lambda emit: run_planner(text, plan, on_event=emit, simulation=simulation), {"mode": mode, "request": text})


@app.post("/api/plan/simulate")
async def plan_simulate(request: Request) -> dict:
    """The plan simulation: sun, movement, space and their scores. Pure geometry, no model calls."""
    body = await request.json()
    plan = clean(body.get("plan"))
    if not plan["rooms"]:
        raise HTTPException(400, "The plan has no rooms to simulate.")
    xs = [r["x"] for r in plan["rooms"]] + [r["x"] + r["w"] for r in plan["rooms"]]
    ys = [r["y"] for r in plan["rooms"]] + [r["y"] + r["h"] for r in plan["rooms"]]
    if (max(xs) - min(xs)) * (max(ys) - min(ys)) > 2500:
        raise HTTPException(400, "The plan is too large to simulate (over 2,500 m² of footprint).")
    settings = body.get("settings") or {}
    try:
        latitude = min(66.0, max(-66.0, float(settings.get("latitude", 28.6))))
        north = float(settings.get("north", 0)) % 360
    except (TypeError, ValueError):
        raise HTTPException(400, "latitude and north must be numbers")
    return simulate(plan, latitude, DAYS.get(settings.get("season"), DAYS["winter"]), north)


